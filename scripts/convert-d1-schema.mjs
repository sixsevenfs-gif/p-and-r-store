import { readFileSync, writeFileSync } from "node:fs";

const [input, output] = process.argv.slice(2);
if (!input || !output) throw new Error("Usage: node convert-d1-schema.mjs INPUT OUTPUT");
const source = readFileSync(input, "utf8");
const excluded = new Set(["d1_migrations", "auth_user", "auth_session", "auth_account", "auth_verification", "auth_rate_limit", "media_assets"]);
const order = ["customers", "newsletter_subscribers", "products", "product_variants", "product_images", "orders", "order_items"];
const creates = [...source.matchAll(/CREATE TABLE\s+[`"]?([a-z_]+)[`"]?\s*\([\s\S]*?\);/gi)]
  .map((match) => ({ name: match[1], sql: match[0] }))
  .filter(({ name }) => !excluded.has(name))
  .sort((a, b) => {
    const ai = order.indexOf(a.name), bi = order.indexOf(b.name);
    return (ai < 0 ? 100 : ai) - (bi < 0 ? 100 : bi);
  });

function convert(sql) {
  return sql
    .replaceAll("`", "")
    .replace(/INTEGER\s+PRIMARY KEY\s+AUTOINCREMENT/gi, "bigint generated by default as identity primary key")
    .replace(/\binteger\s+PRIMARY KEY\s+NOT NULL/gi, "bigint primary key")
    .replace(/\binteger\s+PRIMARY KEY\b/gi, "bigint primary key")
    .replace(/\binteger\b/gi, "bigint")
    .replace(/DEFAULT\s*\(unixepoch\(\)\)/gi, "DEFAULT (extract(epoch from now())::bigint)")
    .replace(/DEFAULT\s+false/gi, "DEFAULT 0")
    .replace(/DEFAULT\s+true/gi, "DEFAULT 1")
    .replace(/ON UPDATE no action/gi, "ON UPDATE NO ACTION")
    .replace(/ON DELETE no action/gi, "ON DELETE NO ACTION");
}

const indexes = source.split("\n")
  .filter((line) => /^CREATE (?:UNIQUE )?INDEX/i.test(line))
  .filter((line) => ![...excluded].some((table) => line.includes(` ${table}_`) || line.includes(` ON ${table}`) || line.includes(` ON \`${table}\``)))
  .map((line) => line.replaceAll("`", ""));

const header = `-- Generated from the final D1 schema for Supabase PostgreSQL.\n-- Run after 0001_auth_storage.sql. Re-running is safe for tables/indexes.\n\n`;
const body = creates.map(({ sql }) => convert(sql).replace(/^CREATE TABLE/i, "CREATE TABLE IF NOT EXISTS")).join("\n\n");
const safeIndexes = indexes.map((line) => line.replace(/^CREATE (UNIQUE )?INDEX/i, (_, unique = "") => `CREATE ${unique}INDEX IF NOT EXISTS`)).join("\n");
writeFileSync(output, `${header}${body}\n\n${safeIndexes}\n`);
