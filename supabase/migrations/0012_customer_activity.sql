-- Admin-visible customer journey events. These are written only for signed-in
-- members and make abandoned bags/checkouts actionable without third-party tracking.
create table if not exists public.customer_activity_events (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers(id) on delete cascade,
  cart_id bigint references public.carts(id) on delete set null,
  event_type text not null check (event_type in ('bag_updated', 'checkout_started', 'order_placed')),
  details jsonb not null default '{}'::jsonb,
  created_at bigint not null default (extract(epoch from now())::bigint)
);

create index if not exists customer_activity_events_customer_idx
  on public.customer_activity_events(customer_id, created_at desc);
create index if not exists customer_activity_events_cart_idx
  on public.customer_activity_events(cart_id, created_at desc);

alter table public.customer_activity_events enable row level security;
